md(
    "## 5. MBR: a tunable accuracy-vs-reach dial\n"
    "\n"
    "First intervention: keep the model frozen, change only how the beam's "
    "candidates are RANKED. Minimum-Bayes-Risk re-ranking prefers candidates "
    "that agree with the model's other guesses (consensus via shared code "
    "prefixes), weighted by the model's own confidence (softmax of candidate "
    "log-probabilities at temperature tau).\n"
    "\n"
    "The verdict from the depth-100 scored runs: MBR is **not an accuracy "
    "fix** (the beam order stays best on R@10), but it is a clean, "
    "serving-time **dial**: sliding tau trades a little accuracy for a lot "
    "of reach. On collapsed Sports, giving up 0.6pp of R@10 buys +13 points "
    "of coverage, a one-quarter drop in average recommendation popularity, "
    "and +32% tail recall (which improves at EVERY tau)."
)

