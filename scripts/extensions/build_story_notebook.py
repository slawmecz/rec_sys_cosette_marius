md(
    "## 7. Fusion ablation\n"
    "\n"
    "MARIUS combines an item's four code embeddings into one history token by "
    "summing them, a choice inherited from audio models that ignores which "
    "digit carried the information. We replaced the sum with level-aware "
    "alternatives (a per-level gain, and a small attention over the four "
    "digits), in a subclass that leaves the authors' code untouched and "
    "matches the baseline exactly at initialization, then retrained on Beauty "
    "(3 seeds).\n"
    "\n"
    "Accuracy is unchanged: the fusion is not the bottleneck, which "
    "concentrates the remaining evidence on the decoding stage. The per-level "
    "gain variant does shift every beyond-accuracy metric slightly in the "
    "favourable direction at no accuracy cost."
)

