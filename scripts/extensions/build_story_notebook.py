md(
    "## 5. MBR re-ranking\n"
    "\n"
    "The first intervention leaves the model frozen and changes only how the "
    "beam's candidates are ranked. Minimum-Bayes-risk re-ranking prefers "
    "candidates that agree with the model's other guesses (measured by shared "
    "code-prefix length), weighted by the model's own confidence at "
    "temperature tau.\n"
    "\n"
    "MBR does not improve accuracy: the original beam order remains best on "
    "Recall@10. It does provide a serving-time trade-off between accuracy and "
    "reach. On Sports, giving up 0.6 points of Recall@10 raises coverage from "
    "0.39 to 0.52, lowers average recommendation popularity from 101 to 73, "
    "and improves tail recall by about a third (at every tau tested)."
)

