md(
    "## 4. REACH: why the collapse happens\n"
    "\n"
    "A generative recommender can only recommend an item whose code it "
    "actually WRITES during beam search. We asked which items the beam can "
    "never write, and why.\n"
    "\n"
    "- **Scale of the damage**: on Sports, 9,260 items (50% of the catalog) "
    "are never recommended by any seed; they carry **22% of all training "
    "demand** (the baseline's unreached set carries 5.7%).\n"
    "- **Where it happens**: not at the first code digit (all 256 are used) "
    "but at digit 2: never-written (digit1, digit2) pairs cover 26% of the "
    "Sports catalog and account for half the unreachable items.\n"
    "- **Why: sibling competition.** The best predictor of unreachability is "
    "an item's popularity share WITHIN its first-digit code family "
    "(r = -0.62), stronger than its own popularity (-0.58). Items lose to "
    "stronger siblings sharing their prefix.\n"
    "- **Robustness**: a second, freshly trained Sports codebook reproduces "
    "all of it within 1-2 points; the collapse is structural, not a "
    "tokenizer-run artifact."
)

