md(
    "## 2. REACH: why MARIUS collapses on Sports\n"
    "\n"
    "**The key idea to hold onto:** a generative recommender can only recommend "
    "an item if it actually *writes that item's 4-digit code* during beam "
    "search. If the beam never writes a code, that item is invisible, no matter "
    "how relevant it would have been. SASRec++ cannot have this problem (it "
    "scores every item directly).\n"
    "\n"
    "So we asked: which items can MARIUS *never* reach, and why? Three findings:\n"
    "\n"
    "1. **The collapse is real and big.** On Sports, 9,260 items (50% of the "
    "catalog) are never recommended to anyone, by any seed. These items carry "
    "**22% of all the demand in the training data** (vs 5.7% for SASRec++): a "
    "fifth of what users provably want is invisible.\n"
    "2. **The beam does not prune whole top-level categories.** All 256 "
    "first-digit codes get used. The collapse happens at **digit 2**: code "
    "*pairs* (digit1, digit2) that the beam never writes cover 26% of the "
    "Sports catalog, and that alone accounts for half the unreachable items.\n"
    "3. **Sibling competition.** The best predictor of being unreachable is not "
    "an item's own popularity but its **popularity share within its "
    "first-digit code family** (r = -0.62 vs -0.58 for own popularity). "
    "Items sharing a prefix compete; the beam follows the strong siblings and "
    "the weak ones never get written, even mid-popularity ones."
)

