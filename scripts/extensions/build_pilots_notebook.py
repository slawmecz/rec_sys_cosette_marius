md(
    "## 5. FUSE: is the sum() an architectural mistake?\n"
    "\n"
    "To feed a user's history into its temporal transformer, MARIUS squashes "
    "each item's 4 code embeddings into ONE vector by simply **adding them up** "
    "(one line: `temp_emb(input).sum(dim=-2)`). That habit was inherited from "
    "audio models. The problem: addition is blind to which digit mattered. Two "
    "items that share their 3 coarse digits and differ only in the fine 4th "
    "digit get almost identical fused vectors, so the model can barely tell "
    "them apart in a user's history (the demo below makes this concrete).\n"
    "\n"
    "We built a subclass (no edits to the authors' code) with three "
    "alternatives, each starting exactly equal to the baseline at "
    "initialization, so training decides if structure helps:\n"
    "\n"
    "- `level_gain`: a learned per-digit volume knob (cheapest fix, +1k params),\n"
    "- `attn`: a tiny attention that re-weights the 4 digits per item (+257 params),\n"
    "- `level_bias`: kept as a control because our selftest PROVED it is a "
    "no-op in disguise (per-digit additive offsets just sum into one constant; "
    "a nice catch that saved a wasted training run).\n"
    "\n"
    "The full 3-seed Beauty runs are complete. Accuracy is unchanged: "
    "`level_gain` reaches R@10 8.29 +/- 0.09 and `attn` reaches 8.23 +/- 0.15, "
    "versus the sum baseline 8.26 +/- 0.20. That makes FUSE a clean negative "
    "for the hypothesis that sum-fusion is the main bottleneck."
)

