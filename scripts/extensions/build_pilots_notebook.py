md(
    "## 4. Conformal sets: turning a weaker model into a reliable one\n"
    "\n"
    "Instead of 'here are 10 guesses', conformal prediction returns a set with "
    "a **statistical guarantee**: 'the true next item is in this set at least "
    "c% of the time'. The guarantee is distribution-free; you calibrate a "
    "set-size threshold on held-out users and it provably transfers.\n"
    "\n"
    "Two honest findings. First, a **ceiling**: with one held-out item per user "
    "and a 20-deep list, the best guaranteeable coverage is the model's "
    "Recall@20 (about 12% on Beauty, 7% on Sports), so conventional 90% "
    "guarantees are impossible here; the realistic product is *small sets with "
    "modest guarantees*. Second, the useful signal: calibrating separately per "
    "user group (Mondrian) makes **set size an uncertainty meter**. On Beauty "
    "it works beautifully: users with long histories need sets of 3; "
    "cold users need 10-12. On Sports the signal is flat-to-inverted, which is "
    "itself evidence of how broken the collapsed regime is."
)

