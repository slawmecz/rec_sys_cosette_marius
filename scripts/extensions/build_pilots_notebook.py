    "## 6. What happens next\n"
    "\n"
    "The completed pilots narrow the next step. The codebook looks healthy, "
    "the sum-fusion ablation is null, and MARIUS has a stronger depth-100 "
    "candidate pool than its top-10 ranking suggests. The decisive missing "
    "experiment is therefore **exact catalog scoring**:\n"
    "\n"
