md(
    "## 3. MBR: re-ranking the beam by consensus\n"
    "\n"
    "MARIUS ranks its 20 beam candidates purely by likelihood ('most probable "
    "first'), which is popularity-biased. **Minimum Bayes Risk (MBR)** is an "
    "old idea from machine translation: instead of the single most probable "
    "guess, prefer the guess that most *agrees* with the model's other "
    "guesses. Here, two candidates 'agree' if their codes share a long prefix "
    "(they sit in the same branch of the code tree).\n"
    "\n"
    "Tonight we could only run the **uniform-weight** version (every candidate "
    "votes equally, because the dumps did not store the model's confidence "
    "scores yet); this is the method's known *lower bound*: accuracy is "
    "expected to dip. The interesting question was whether the *diversity* "
    "side responds, and it does, on every metric, on both datasets; on the "
    "collapsed Sports dataset, even tail accuracy improves on every seed. The "
    "score-weighted version (the real accuracy test) runs on Snellius "
    "tonight."
)

