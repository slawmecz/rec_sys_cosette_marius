md(
    "## 4. Conformal sets: turning a weaker model into a reliable one\n"
    "\n"
    "Instead of 'here are 10 guesses', conformal prediction returns a set with "
    "a **statistical guarantee**: 'the true next item is in this set at least "
    "c% of the time'. The guarantee is distribution-free; you calibrate a "
    "set-size threshold on held-out users and it provably transfers.\n"
    "\n"
    "Two honest findings. First, a **ceiling**: with one held-out item per user, "
    "the best guaranteeable coverage is the model's Recall at the dump depth, "
    "so conventional 90% guarantees are impossible here. Depth 100 roughly "
    "doubles the ceiling and creates a useful crossover: at depth 20 SASRec++ "
    "has the higher ceiling, but at depth 100 MARIUS does on both datasets. "
    "Second, calibrating separately per user group (Mondrian) makes **set size "
    "an uncertainty meter**. On Beauty, cold users need much larger sets than "
    "warm users; on Sports the signal is flatter, consistent with the collapse."
)

